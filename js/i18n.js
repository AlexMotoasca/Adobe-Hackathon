export const PLACEHOLDER_STRINGS = ["Exact product model", "verified local price", "Confirmed offer terms", "Verified product benefit", "source", "exact product model", "verified benefit or specification", "verified figure"];
const VERSION = 'v4';

export function translator(dict = {}) {
  return (text, vars = {}) => {
    let out = dict[text] || text;
    for (const [key, value] of Object.entries(vars)) out = out.split('{' + key + '}').join(String(value));
    return out;
  };
}

// Loads (and remembers in this browser) the UI translation for a report language.
export async function loadTranslator(language) {
  if (!language || /^english$/i.test(language)) return translator();
  const key = 'mm-i18n:' + VERSION + ':' + language;
  try { const saved = JSON.parse(localStorage.getItem(key) || 'null'); if (saved) return translator(saved); } catch {}
  try {
    const ask = strings => request('/i18n', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({language, strings}), signal: AbortSignal.timeout(90000)});
    const [labels, fills] = await Promise.all([ask(UI_STRINGS), ask(PLACEHOLDER_STRINGS).catch(() => ({strings: {}, complete: false}))]);
    const dict = {...labels.strings, ...fills.strings};
    if (labels.complete !== false && fills.complete !== false) { try { localStorage.setItem(key, JSON.stringify(dict)); } catch {} }
    return translator(dict);
  } catch { return translator(); } // English labels if translation is unavailable
}
